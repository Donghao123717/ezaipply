export interface CollegeDbEntry {
  id: string
  name: string
  code: string
  /** Approximate overall undergraduate acceptance rate (0-100). Illustrative
   * figures from general knowledge of recent admissions cycles, not a live
   * or certified data feed - good enough to anchor a demo forecast, not to
   * cite as an official statistic. Where a school also appears in
   * lib/school-admissions-data.ts, that file's IPEDS-checked figure is the
   * one shown in the UI. */
  acceptanceRate: number
  /** US News 2026 National Universities rank, where the school is in that
   * ranking. Liberal arts colleges are ranked on a separate US News list and
   * carry no rank here - their absence is not a low placement. */
  usNewsRank?: number
}

