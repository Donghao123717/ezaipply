function codeFor(name: string, index: number): string {
  let hash = 0
  for (let i = 0; i < name.length; i++) {
    hash = (hash * 31 + name.charCodeAt(i)) >>> 0
  }
  return String(1000 + ((hash + index * 7) % 9000)).padStart(4, '0')
}

